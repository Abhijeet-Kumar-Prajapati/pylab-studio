"""
Ascii Art Banner
Category: Loops/Pattern

Prints a small ASCII art banner in the console.

Example:
    Prints a cat face and a happy face.
"""

CAT = r"""
 /\_/\
( o.o )
 > ^ <
"""

HAPPY = r"""
   /\_/\    .-."
  (   )  (   )
  ( '-' )  )
   \   /  .'
"""


def main():
    """Print the ASCII art."""
    print(CAT)
    print(HAPPY)


if __name__ == "__main__":
    main()